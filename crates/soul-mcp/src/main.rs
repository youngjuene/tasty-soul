//! `soul-mcp` — 로컬 MCP 서버 (§19).
//!
//! ## 절대 규칙
//!
//! **이 바이너리에 HTTP 클라이언트를 링크하지 않는다** (§19.4, T32).
//! 의존성은 `soul-core` + `serde` + `serde_json` 뿐이다. MCP 프로토콜은 stdio JSON-RPC
//! 2.0이므로 직접 구현하며, SDK를 추가하지 않는다 — 추가하면 전이 의존으로 네트워크
//! 클라이언트가 끌려들어올 수 있다.
//!
//! **쓰기 툴을 제공하지 않는다** (§19.6, T34). 로컬 에이전트가 관측 로그에 기록을 남기면
//! 사람이 투입한 것과 모델이 만든 것이 섞이고, 취향 모델이 자기 출력으로 오염된다.
//! 서버는 `soul/`을 **읽기 전용**으로 연다 (T35).
//!
//! 본체는 `lib.rs`에 있다 — 통합 테스트가 바이너리 크레이트의 모듈을 볼 수 없기 때문이다.

fn main() -> anyhow::Result<()> {
    soul_mcp::server::run_stdio()
}
